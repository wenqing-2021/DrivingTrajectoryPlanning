#!/usr/bin/env python3
"""
OBCA Planner Result Visualization Script

This script reads CSV files generated by test_obca_main.cpp and creates
visualization plots of the OBCA planning results.
"""

import os
import csv
import sys
import matplotlib.pyplot as plt
import matplotlib.patches as patches
import numpy as np
from pathlib import Path

# Vehicle parameters (should match the C++ code)
VEHICLE_LENGTH = 5.0  # meters
VEHICLE_WIDTH = 2.0  # meters
REAR_OVERHANG = 1.25  # meters


def load_csv(filename):
    """Load data from CSV file."""
    data = []
    try:
        with open(filename, "r") as f:
            reader = csv.reader(f)
            header = next(reader)  # Skip header
            for row in reader:
                data.append([float(x) for x in row])
        return np.array(data), header
    except FileNotFoundError:
        print(f"Warning: File not found: {filename}")
        return None, None
    except Exception as e:
        print(f"Error reading {filename}: {e}")
        return None, None


def load_polygon(filename):
    """Load polygon (obstacle) from CSV file."""
    data, _ = load_csv(filename)
    return data


def load_all_obstacles(results_dir):
    """Load all obstacles from the results directory."""
    obstacles = []
    i = 0
    while True:
        obstacle_file = os.path.join(results_dir, f"obstacle_{i}.csv")
        if not os.path.exists(obstacle_file):
            break
        polygon = load_polygon(obstacle_file)
        if polygon is not None:
            obstacles.append(polygon)
        i += 1
    return obstacles


def get_vehicle_corners(
    x,
    y,
    theta,
    length=VEHICLE_LENGTH,
    width=VEHICLE_WIDTH,
    rear_overhang=REAR_OVERHANG,
):
    """Calculate the four corners of the vehicle rectangle.

    Args:
        x: x-coordinate of rear axle center
        y: y-coordinate of rear axle center
        theta: heading angle in radians
        length: vehicle length
        width: vehicle width
        rear_overhang: rear axle center to rear bumper distance

    Returns:
        numpy array of shape (5, 2) containing the four corners and closing point
    """
    # Vehicle corners in local frame (rear axle center at origin, facing +x)
    # Longitudinal range: [-rear_overhang, length - rear_overhang]
    front_x = length - rear_overhang
    rear_x = -rear_overhang
    half_width = width / 2.0

    corners_local = np.array(
        [
            [front_x, -half_width],  # Front-right
            [front_x, half_width],  # Front-left
            [rear_x, half_width],  # Rear-left
            [rear_x, -half_width],  # Rear-right
            [front_x, -half_width],  # Close the rectangle
        ]
    )

    # Rotation matrix
    cos_theta = np.cos(theta)
    sin_theta = np.sin(theta)
    rotation_matrix = np.array([[cos_theta, -sin_theta], [sin_theta, cos_theta]])

    # Transform to global frame
    corners_global = corners_local @ rotation_matrix.T
    corners_global[:, 0] += x
    corners_global[:, 1] += y

    return corners_global


def create_visualization(results_dir, output_file="obca_result.png"):
    """Create visualization of OBCA planning results."""

    print(f"Loading data from {results_dir}...")

    # Load all data
    initial_path, _ = load_csv(os.path.join(results_dir, "initial_path.csv"))
    optimized_traj, _ = load_csv(os.path.join(results_dir, "optimized_trajectory.csv"))
    optimized_controls, _ = load_csv(
        os.path.join(results_dir, "optimized_controls.csv")
    )
    start_goal, _ = load_csv(os.path.join(results_dir, "start_goal.csv"))

    # Load obstacles
    obstacles = load_all_obstacles(results_dir)

    if optimized_traj is None:
        print("Error: Could not load optimized trajectory. Exiting.")
        # return False

    # Create figure with subplots: trajectory plot, velocity plot, and control plots
    fig = plt.figure(figsize=(16, 10))
    gs = fig.add_gridspec(3, 2, hspace=0.3, wspace=0.3)
    ax_traj = fig.add_subplot(
        gs[0:2, :]
    )  # Top: trajectory (spans 2 rows and all columns)
    ax_vel = fig.add_subplot(gs[2, 0])  # Bottom left: velocity
    ax_control = fig.add_subplot(gs[2, 1])  # Bottom right: controls

    # ========== Plot 1: Trajectory ==========
    ax = ax_traj  # Use ax for trajectory plot for compatibility with existing code

    # Plot initial path
    if initial_path is not None:
        ax.plot(
            initial_path[:, 0],
            initial_path[:, 1],
            "b--",
            linewidth=2,
            label="Initial Path (Rear Axle)",
            alpha=0.7,
        )
        ax.plot(initial_path[:, 0], initial_path[:, 1], "bo", markersize=4, alpha=0.5)

        # Draw vehicle bounding boxes along the initial path
        # Draw every N states to avoid cluttering
        step = max(1, len(initial_path) // 10)  # Draw ~10 vehicles
        for i in range(0, len(initial_path), step):
            x, y, theta = initial_path[i, 0], initial_path[i, 1], initial_path[i, 2]
            corners = get_vehicle_corners(x, y, theta)

            # Draw vehicle rectangle
            vehicle_rect = patches.Polygon(
                corners[:-1],
                closed=True,
                facecolor="blue",
                edgecolor="darkblue",
                linewidth=1.5,
                alpha=0.15,
                zorder=2,
            )
            ax.add_patch(vehicle_rect)

            # Draw vehicle outline
            ax.plot(corners[:, 0], corners[:, 1], "b--", linewidth=1.0, alpha=0.5)

    # Plot optimized trajectory
    if optimized_traj is not None:
        ax.plot(
            optimized_traj[:, 0],
            optimized_traj[:, 1],
            "g-",
            linewidth=2.5,
            label="Optimized Trajectory (Rear Axle)",
        )
        ax.plot(
            optimized_traj[:, 0], optimized_traj[:, 1], "go", markersize=6, alpha=0.6
        )

        # Draw vehicle bounding boxes along the trajectory
        # Draw every N states to avoid cluttering
        step = max(1, len(optimized_traj) // 10)  # Draw ~10 vehicles
        for i in range(0, len(optimized_traj), step):
            x, y, theta = (
                optimized_traj[i, 0],
                optimized_traj[i, 1],
                optimized_traj[i, 2],
            )
            corners = get_vehicle_corners(x, y, theta)

            # Draw vehicle rectangle
            vehicle_rect = patches.Polygon(
                corners[:-1],
                closed=True,
                facecolor="green",
                edgecolor="darkgreen",
                linewidth=1.5,
                alpha=0.2,
                zorder=3,
            )
            ax.add_patch(vehicle_rect)

            # Draw vehicle outline
            ax.plot(corners[:, 0], corners[:, 1], "g-", linewidth=1.5, alpha=0.6)

        # Draw vehicle at start and end positions with different colors
        if len(optimized_traj) > 0:
            # Start vehicle
            x, y, theta = (
                optimized_traj[0, 0],
                optimized_traj[0, 1],
                optimized_traj[0, 2],
            )
            corners_start = get_vehicle_corners(x, y, theta)
            vehicle_start = patches.Polygon(
                corners_start[:-1],
                closed=True,
                facecolor="blue",
                edgecolor="darkblue",
                linewidth=2,
                alpha=0.4,
                zorder=4,
                label="Start Vehicle",
            )
            ax.add_patch(vehicle_start)

            # End vehicle
            x, y, theta = (
                optimized_traj[-1, 0],
                optimized_traj[-1, 1],
                optimized_traj[-1, 2],
            )
            corners_end = get_vehicle_corners(x, y, theta)
            vehicle_end = patches.Polygon(
                corners_end[:-1],
                closed=True,
                facecolor="red",
                edgecolor="darkred",
                linewidth=2,
                alpha=0.4,
                zorder=4,
                label="End Vehicle",
            )
            ax.add_patch(vehicle_end)

    # Plot start and goal
    if start_goal is not None and len(start_goal) >= 2:
        ax.plot(
            start_goal[0, 0],
            start_goal[0, 1],
            "g^",
            markersize=15,
            label="Start",
            zorder=5,
        )
        ax.plot(
            start_goal[1, 0],
            start_goal[1, 1],
            "r*",
            markersize=20,
            label="Goal",
            zorder=5,
        )

    # Plot obstacles
    colors = plt.cm.Reds(np.linspace(0.3, 0.7, len(obstacles)))
    for i, obstacle in enumerate(obstacles):
        # Draw filled polygon
        polygon = patches.Polygon(
            obstacle[:-1],
            closed=True,
            facecolor=colors[i],
            edgecolor="darkred",
            linewidth=2,
            alpha=0.3,
        )
        ax.add_patch(polygon)
        # Draw polygon boundary
        if len(obstacle) > 0:
            ax.plot(obstacle[:, 0], obstacle[:, 1], "r--", linewidth=2, alpha=0.8)

    # Set labels and title for trajectory plot
    ax.set_xlabel("X (m)", fontsize=12)
    ax.set_ylabel("Y (m)", fontsize=12)
    ax.set_title("OBCA Path Planning Result", fontsize=14, fontweight="bold")
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=10, loc="upper left", ncol=2)
    ax.set_aspect("equal", adjustable="box")
    ax.margins(0.1)

    # ========== Plot 2: Velocity Profile ==========
    if optimized_traj is not None:
        # Calculate path distance
        x_pos = optimized_traj[:, 0]
        y_pos = optimized_traj[:, 1]
        velocity = optimized_traj[:, 3]

        # Calculate cumulative distance
        distances = np.zeros(len(x_pos))
        for i in range(1, len(x_pos)):
            distances[i] = distances[i - 1] + np.sqrt(
                (x_pos[i] - x_pos[i - 1]) ** 2 + (y_pos[i] - y_pos[i - 1]) ** 2
            )

        # Plot velocity vs distance
        ax_vel.plot(distances, velocity, "b-", linewidth=2.5, label="Velocity")
        ax_vel.fill_between(distances, 0, velocity, alpha=0.3, color="blue")
        ax_vel.set_xlabel("Distance along path (m)", fontsize=11)
        ax_vel.set_ylabel("Velocity (m/s)", fontsize=11)
        ax_vel.set_title("Velocity Profile", fontsize=12, fontweight="bold")
        ax_vel.grid(True, alpha=0.3)
        ax_vel.legend(fontsize=10)

        # Add max velocity line
        max_v = VEHICLE_LENGTH if "VEHICLE_LENGTH" in dir() else 5.0
        max_velocity_limit = 5.0  # From C++ code
        ax_vel.axhline(
            y=max_velocity_limit,
            color="r",
            linestyle="--",
            linewidth=1.5,
            alpha=0.7,
            label=f"Max Velocity ({max_velocity_limit} m/s)",
        )
        ax_vel.legend(fontsize=10)

    # ========== Plot 3: Control Inputs ==========
    if optimized_controls is not None and len(optimized_controls) > 0:
        acceleration = optimized_controls[:, 0]
        steer_angle = optimized_controls[:, 1]
        control_indices = np.arange(len(acceleration))

        # Create twin axis for steering angle
        ax_control_twin = ax_control.twinx()

        # Plot acceleration
        line1 = ax_control.plot(
            control_indices,
            acceleration,
            "g-",
            linewidth=2.5,
            label="Acceleration",
            alpha=0.8,
        )
        ax_control.fill_between(
            control_indices, 0, acceleration, alpha=0.2, color="green"
        )
        ax_control.set_xlabel("Control Step", fontsize=11)
        ax_control.set_ylabel("Acceleration (m/s²)", fontsize=11, color="g")
        ax_control.tick_params(axis="y", labelcolor="g")
        ax_control.grid(True, alpha=0.3)

        # Plot steering angle on twin axis
        line2 = ax_control_twin.plot(
            control_indices,
            np.degrees(steer_angle),
            "orange",
            linewidth=2.5,
            label="Steering Angle",
            alpha=0.8,
        )
        ax_control_twin.set_ylabel(
            "Steering Angle (degrees)", fontsize=11, color="orange"
        )
        ax_control_twin.tick_params(axis="y", labelcolor="orange")

        # Add limits
        max_acc = 2.0  # From C++ code
        max_steer = np.degrees(0.5)  # From C++ code
        ax_control.axhline(
            y=max_acc, color="darkgreen", linestyle="--", linewidth=1.5, alpha=0.5
        )
        ax_control.axhline(
            y=-max_acc, color="darkgreen", linestyle="--", linewidth=1.5, alpha=0.5
        )
        ax_control_twin.axhline(
            y=max_steer, color="darkorange", linestyle="--", linewidth=1.5, alpha=0.5
        )
        ax_control_twin.axhline(
            y=-max_steer, color="darkorange", linestyle="--", linewidth=1.5, alpha=0.5
        )

        ax_control.set_title("Control Inputs", fontsize=12, fontweight="bold")

        # Combined legend
        lines = line1 + line2
        labels = [l.get_label() for l in lines]
        ax_control.legend(lines, labels, fontsize=10, loc="upper right")

    # Save figure
    plt.tight_layout()
    plt.savefig(output_file, dpi=150, bbox_inches="tight")
    print(f"✓ Visualization saved to: {output_file}")

    return True


def print_statistics(results_dir):
    """Print statistics about the planning results."""

    print("\n" + "=" * 60)
    print("OBCA Planning Results Summary")
    print("=" * 60)

    # Load trajectory
    optimized_traj, _ = load_csv(os.path.join(results_dir, "optimized_trajectory.csv"))
    optimized_controls, _ = load_csv(
        os.path.join(results_dir, "optimized_controls.csv")
    )
    initial_path, _ = load_csv(os.path.join(results_dir, "initial_path.csv"))

    if optimized_traj is None:
        print("Error: Could not load trajectory data.")
        return

    # Extract x, y positions
    x_pos = optimized_traj[:, 0]
    y_pos = optimized_traj[:, 1]
    theta = optimized_traj[:, 2]
    v = optimized_traj[:, 3]

    # Calculate path length
    path_length = 0
    for i in range(1, len(x_pos)):
        path_length += np.sqrt(
            (x_pos[i] - x_pos[i - 1]) ** 2 + (y_pos[i] - y_pos[i - 1]) ** 2
        )

    # Statistics
    print(f"\nTrajectory Statistics:")
    print(f"  Number of states: {len(optimized_traj)}")
    print(
        f"  Number of controls: {len(optimized_controls) if optimized_controls is not None else 0}"
    )
    print(f"\nStart Position:")
    print(f"  x = {x_pos[0]:.4f} m")
    print(f"  y = {y_pos[0]:.4f} m")
    print(f"\nEnd Position:")
    print(f"  x = {x_pos[-1]:.4f} m")
    print(f"  y = {y_pos[-1]:.4f} m")
    print(f"\nGoal Position:")
    print(f"  x = 30.0000 m")
    print(f"  y = 0.0000 m")
    print(f"\nPosition Error:")
    print(f"  dx = {abs(x_pos[-1] - 30.0):.6f} m")
    print(f"  dy = {abs(y_pos[-1] - 0.0):.6f} m")
    print(f"\nPath Metrics:")
    print(f"  Path length: {path_length:.4f} m")
    print(f"  Max heading: {np.max(np.abs(theta)):.6f} rad")
    print(f"  Max velocity: {np.max(v):.6f} m/s")

    if optimized_controls is not None:
        acc = optimized_controls[:, 0]
        steer = optimized_controls[:, 1]
        print(f"\nControl Statistics:")
        print(f"  Max acceleration: {np.max(np.abs(acc)):.6f} m/s²")
        print(f"  Max steering angle: {np.max(np.abs(steer)):.6f} rad")

    print("\n" + "=" * 60 + "\n")


def main():
    """Main visualization function."""

    # Default results directory
    results_dir = "/tmp/obca_test_results"

    # Allow custom directory as command line argument
    if len(sys.argv) > 1:
        results_dir = sys.argv[1]

    # Check if results directory exists
    if not os.path.isdir(results_dir):
        print(f"Error: Results directory not found: {results_dir}")
        print("Please run test_obca_main first to generate results.")
        return 1

    print(f"Results directory: {results_dir}")

    # Print statistics
    print_statistics(results_dir)

    # Create visualization
    output_file = os.path.join(results_dir, "obca_result.png")
    success = create_visualization(results_dir, output_file)

    if success:
        print(f"\nVisualization complete!")
        print(f"Results saved to: {results_dir}")

        # Try to display the image
        try:
            import subprocess

            subprocess.Popen(["display", output_file])
        except:
            pass

        return 0
    else:
        return 1


if __name__ == "__main__":
    sys.exit(main())
