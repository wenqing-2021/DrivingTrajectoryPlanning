#!/usr/bin/env python3
"""
RDA Planner Result Visualization Script

Reads CSV files generated by test_rda_main.cpp and creates a comparison plot of
the initial (reference) path vs. the RDA-optimized trajectory, together with the
velocity profile. Adapted from visualize_obca_result.py.
"""

import os
import csv
import argparse
import matplotlib.pyplot as plt
import matplotlib.patches as patches
import numpy as np

# Vehicle parameters (must match test_rda_main.cpp, same as OBCA test)
VEHICLE_LENGTH = 5.0      # meters
VEHICLE_WIDTH = 2.0       # meters
REAR_OVERHANG = 1.25      # meters
MAX_VELOCITY = 5.0        # m/s


def load_csv(filename):
    """Load data from CSV file (skip header)."""
    try:
        with open(filename, "r") as f:
            reader = csv.reader(f)
            next(reader)  # skip header
            data = [[float(x) for x in row] for row in reader]
        return np.array(data)
    except FileNotFoundError:
        print(f"Warning: file not found: {filename}")
        return None


def load_all_obstacles(results_dir):
    obstacles = []
    i = 0
    while True:
        f = os.path.join(results_dir, f"obstacle_{i}.csv")
        if not os.path.exists(f):
            break
        poly = load_csv(f)
        if poly is not None:
            obstacles.append(poly)
        i += 1
    return obstacles


def get_vehicle_corners(x, y, theta,
                        length=VEHICLE_LENGTH,
                        width=VEHICLE_WIDTH,
                        rear_overhang=REAR_OVERHANG):
    """Vehicle rectangle corners (rear-axle center at origin, facing +x)."""
    front_x = length - rear_overhang
    rear_x = -rear_overhang
    hw = width / 2.0
    corners_local = np.array([
        [front_x, -hw],
        [front_x,  hw],
        [rear_x,   hw],
        [rear_x,  -hw],
        [front_x, -hw],
    ])
    c, s = np.cos(theta), np.sin(theta)
    R = np.array([[c, -s], [s, c]])
    corners = corners_local @ R.T
    corners[:, 0] += x
    corners[:, 1] += y
    return corners


def create_visualization(results_dir, output_file="rda_result.png"):
    print(f"Loading data from {results_dir} ...")

    initial_traj = load_csv(os.path.join(results_dir, "initial_trajectory.csv"))
    optimized_traj = load_csv(os.path.join(results_dir, "optimized_trajectory.csv"))
    obstacles = load_all_obstacles(results_dir)

    if optimized_traj is None:
        print("Error: optimized_trajectory.csv not found.")
        return False

    fig = plt.figure(figsize=(16, 9))
    gs = fig.add_gridspec(2, 2, hspace=0.28, wspace=0.25)
    ax_traj = fig.add_subplot(gs[0, :])     # top: trajectory comparison
    ax_vel = fig.add_subplot(gs[1, 0])      # bottom-left: velocity
    ax_dev = fig.add_subplot(gs[1, 1])      # bottom-right: lateral deviation

    # ================= Trajectory comparison =================
    ax = ax_traj
    if initial_traj is not None:
        ax.plot(initial_traj[:, 0], initial_traj[:, 1], "b--", lw=2,
                label="Initial Path (reference)", alpha=0.7)
        ax.plot(initial_traj[:, 0], initial_traj[:, 1], "b.", ms=4, alpha=0.4)

    ax.plot(optimized_traj[:, 0], optimized_traj[:, 1], "g-", lw=2.5,
            label="RDA Optimized Trajectory")
    ax.plot(optimized_traj[:, 0], optimized_traj[:, 1], "go", ms=5, alpha=0.6)

    # Vehicle boxes along optimized trajectory
    step = max(1, len(optimized_traj) // 12)
    for i in range(0, len(optimized_traj), step):
        x, y, th = optimized_traj[i, 0], optimized_traj[i, 1], optimized_traj[i, 2]
        corners = get_vehicle_corners(x, y, th)
        ax.add_patch(patches.Polygon(corners[:-1], closed=True, facecolor="green",
                                     edgecolor="darkgreen", lw=1.2, alpha=0.18, zorder=3))
        ax.plot(corners[:, 0], corners[:, 1], "g-", lw=1.0, alpha=0.5)

    # Start / goal vehicle
    sx, sy, sth = optimized_traj[0, 0], optimized_traj[0, 1], optimized_traj[0, 2]
    ax.add_patch(patches.Polygon(get_vehicle_corners(sx, sy, sth)[:-1], closed=True,
                                 facecolor="blue", edgecolor="darkblue", lw=2, alpha=0.4,
                                 zorder=4, label="Start Vehicle"))
    ex, ey, eth = optimized_traj[-1, 0], optimized_traj[-1, 1], optimized_traj[-1, 2]
    ax.add_patch(patches.Polygon(get_vehicle_corners(ex, ey, eth)[:-1], closed=True,
                                 facecolor="red", edgecolor="darkred", lw=2, alpha=0.4,
                                 zorder=4, label="End Vehicle"))

    ax.plot(sx, sy, "g^", ms=15, label="Start", zorder=5)
    ax.plot(ex, ey, "r*", ms=20, label="Goal", zorder=5)

    # Obstacles
    colors = plt.cm.Reds(np.linspace(0.35, 0.7, max(1, len(obstacles))))
    for i, obs in enumerate(obstacles):
        ax.add_patch(patches.Polygon(obs[:-1], closed=True, facecolor=colors[i],
                                     edgecolor="darkred", lw=2, alpha=0.35, zorder=2))
        ax.plot(obs[:, 0], obs[:, 1], "r--", lw=2, alpha=0.8)

    ax.set_xlabel("X (m)")
    ax.set_ylabel("Y (m)")
    ax.set_title("RDA Path Planning Result: Initial vs Optimized", fontweight="bold")
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=9, loc="upper left", ncol=2)
    ax.set_aspect("equal", adjustable="box")
    ax.margins(0.1)

    # ================= Velocity profile =================
    v = optimized_traj[:, 3]
    steps = np.arange(len(v))
    ax_vel.plot(steps, v, "b-", lw=2.5, label="Velocity")
    ax_vel.fill_between(steps, 0, v, alpha=0.25, color="blue")
    ax_vel.axhline(MAX_VELOCITY, color="r", ls="--", lw=1.5, alpha=0.7,
                   label=f"Max Velocity ({MAX_VELOCITY} m/s)")
    ax_vel.set_xlabel("Step")
    ax_vel.set_ylabel("Velocity (m/s)")
    ax_vel.set_title("Velocity Profile", fontweight="bold")
    ax_vel.grid(True, alpha=0.3)
    ax_vel.legend(fontsize=9)

    # ================= Lateral deviation =================
    if initial_traj is not None:
        dev = optimized_traj[:, 1] - initial_traj[:, 1]
        ax_dev.plot(steps, dev, "m-", lw=2.5, label="Lateral deviation (opt - init)")
        ax_dev.axhline(0, color="k", ls="-", lw=0.8, alpha=0.5)
        ax_dev.fill_between(steps, 0, dev, alpha=0.2, color="m")
        ax_dev.set_xlabel("Step")
        ax_dev.set_ylabel("Y deviation (m)")
        ax_dev.set_title("Obstacle-Avoidance Deviation", fontweight="bold")
        ax_dev.grid(True, alpha=0.3)
        ax_dev.legend(fontsize=9)

    plt.tight_layout()
    plt.savefig(output_file, dpi=150, bbox_inches="tight")
    print(f"Saved visualization to: {output_file}")
    return True


def print_statistics(results_dir):
    optimized_traj = load_csv(os.path.join(results_dir, "optimized_trajectory.csv"))
    initial_traj = load_csv(os.path.join(results_dir, "initial_trajectory.csv"))
    if optimized_traj is None:
        return
    print("\n" + "=" * 55)
    print("RDA Planning Results Summary")
    print("=" * 55)
    print(f"  Steps                : {len(optimized_traj)}")
    print(f"  Final position       : ({optimized_traj[-1,0]:.3f}, {optimized_traj[-1,1]:.3f})")
    print(f"  Max |velocity|       : {np.abs(optimized_traj[:,3]).max():.3f} m/s")
    if initial_traj is not None:
        dev = np.abs(optimized_traj[:, 1] - initial_traj[:, 1]).max()
        print(f"  Max lateral deviation: {dev:.3f} m")
    print("=" * 55 + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Visualize RDA planning results")
    parser.add_argument("--results_dir", default="/tmp/rda_test_results",
                        help="Directory containing CSV result files")
    parser.add_argument("--output", default="/tmp/rda_test_results/rda_result.png",
                        help="Output image file")
    args = parser.parse_args()

    print_statistics(args.results_dir)
    create_visualization(args.results_dir, args.output)
